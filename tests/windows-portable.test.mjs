import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, copyFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { windowsConfiguration, configureWindows } from "../portable/configure-windows.mjs";
const root = fileURLToPath(new URL("../", import.meta.url));
test("native Windows profile uses PowerShell, native MCP executables and local browser paths", () => {
  const { settings, mcp, browser } = windowsConfiguration(root, "C:\\Program Files\\Git\\bin\\bash.exe");
  assert.ok(settings.defaultTools.includes("+powershell"));
  assert.ok(settings.defaultTools.includes("-bash"));
  assert.equal(settings.shellPath, "C:\\Program Files\\Git\\bin\\bash.exe");
  assert.deepEqual(Object.keys(mcp.mcpServers).sort(), ["oomagent-test", "playwright", "serena"]);
  for (const server of Object.values(mcp.mcpServers)) assert.match(server.command, /\.exe$/);
  assert.ok(browser.outputDir.startsWith(join(root, ".portable/windows")));
  assert.equal(browser.browser.isolated, true);
  assert.ok(settings.extensions.includes(join(root, ".pi/extensions/oomagent-ui.ts")));
});
test("Windows generation preserves settings/auth and does not create Projects or touch Linux state", t => {
  const dir = mkdtempSync(join(tmpdir(), "pi-windows-"));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  mkdirSync(join(dir, ".pi/extensions"), { recursive: true });
  for (const file of ["system-prompt.md", "playwright-mcp.json"]) copyFileSync(join(root, ".pi", file), join(dir, ".pi", file));
  configureWindows(dir, "C:\\Git\\bin\\bash.exe");
  const settings = join(dir, ".portable/windows/agent/settings.json");
  writeFileSync(settings, '{"custom":true}');
  const auth = join(dir, ".portable/windows/agent/auth.json");
  writeFileSync(auth, '{"fixture":true}');
  configureWindows(dir, "C:\\Other\\bash.exe");
  assert.equal(readFileSync(settings, "utf8"), '{"custom":true}');
  assert.equal(readFileSync(auth, "utf8"), '{"fixture":true}');
  assert.throws(() => readFileSync(join(dir, "Projects")), /ENOENT/);
  assert.throws(() => readFileSync(join(dir, ".portable/agent/settings.json")), /ENOENT/);
});
test("Windows launchers use the pinned custom source, preserve cwd and isolate repository MCP defaults", () => {
  const pi = readFileSync(join(root, "pi.cmd"), "utf8");
  assert.match(pi, /pi-source\\packages\\coding-agent\\dist\\cli.js/);
  assert.match(pi, /--no-approve/);
  assert.doesNotMatch(pi, /\bcd\s/i);
  const setup = readFileSync(join(root, "setup.ps1"), "utf8");
  assert.match(setup, /Get-FileHash/);
  assert.match(setup, /b4afdddf44e059c67ccf5097e5317d913521b470/);
  assert.match(setup, /build:offline/);
  assert.doesNotMatch(setup, /wsl\.exe|apt-get|Invoke-Expression/);
});
